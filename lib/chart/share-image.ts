import { Resvg } from "@resvg/resvg-js"
import path from "path"

function escapeXml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;")
}

interface ShareBirthInfo {
  date?: string
  time?: string
  locationName?: string
}

// Brand fonts are bundled: serverless environments ship no usable system
// fonts, so text would silently vanish from rendered images.
const FONT_FILES = [
  path.join(process.cwd(), "lib/fonts/Jost-Regular.ttf"),
  path.join(process.cwd(), "lib/fonts/Montserrat-Regular.ttf"),
  path.join(process.cwd(), "lib/fonts/Montserrat-Medium.ttf"),
]

/**
 * Renders the 1200×630 social-share card (OG image size) with both chart
 * wheels, brand header, and birth details — the image people actually share.
 */
export async function renderShareImage(
  chartSvgs: { vedic?: string; western?: string } | null,
  birthInfo: ShareBirthInfo | null,
): Promise<Buffer | null> {
  const vedic = chartSvgs?.vedic
  const western = chartSvgs?.western
  if (!vedic && !western) return null

  const subtitle = [birthInfo?.date, birthInfo?.time, birthInfo?.locationName]
    .filter(Boolean)
    .join(" · ")

  const wheel = (svg: string | undefined, x: number) =>
    svg ? `<g transform="translate(${x},180) scale(1.11)">${svg}</g>` : ""

  const card = `<svg width="1200" height="630" viewBox="0 0 1200 630" xmlns="http://www.w3.org/2000/svg">
  <rect width="1200" height="630" fill="#1F1208" />
  <text x="600" y="64" text-anchor="middle" fill="#EC9247" font-size="26" font-family="Jost" letter-spacing="6">SOLIVANA ASTRO</text>
  <text x="600" y="108" text-anchor="middle" fill="#F0EDED" font-size="38" font-family="Jost">Vedic + Western Natal Chart</text>
  <text x="600" y="148" text-anchor="middle" fill="#B49F90" font-size="21" font-family="Montserrat">${escapeXml(subtitle)}</text>
  ${wheel(vedic, 120)}
  ${wheel(western, 680)}
  <text x="600" y="610" text-anchor="middle" fill="#786455" font-size="16" font-family="Montserrat">astro.solivana.io · Generated by SoliVana AI</text>
</svg>`

  const resvg = new Resvg(card, {
    font: { fontFiles: FONT_FILES, loadSystemFonts: false },
  })
  return resvg.render().asPng()
}
