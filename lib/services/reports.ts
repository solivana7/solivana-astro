const INK = "#1F1208"
const BODY = "#331D01"
const MARGIN = 72 // 1 inch in points; DOCX margins use MARGIN * 20 for twips

// Required AI disclosure, appended to every exported report.
const AI_DISCLOSURE =
  "Generated by SoliVana AI — for reflection and education, not advice. Your reading expires 30 days after creation."

interface MarkdownBlock {
  type: "heading" | "paragraph"
  level: number
  text: string
}

interface ParsedRun {
  text: string
  bold: boolean
}

function parseBoldRuns(text: string): ParsedRun[] {
  const runs: ParsedRun[] = []
  const pattern = /\*\*(.+?)\*\*/g
  let lastIndex = 0
  let match: RegExpExecArray | null

  while ((match = pattern.exec(text)) !== null) {
    if (match.index > lastIndex) {
      runs.push({ text: text.slice(lastIndex, match.index), bold: false })
    }
    runs.push({ text: match[1], bold: true })
    lastIndex = match.index + match[0].length
  }

  if (lastIndex < text.length) {
    runs.push({ text: text.slice(lastIndex), bold: false })
  }

  if (runs.length === 0) {
    runs.push({ text, bold: false })
  }

  return runs
}

function parseMarkdownBlocks(markdown: string): MarkdownBlock[] {
  const lines = markdown.split("\n")
  const blocks: MarkdownBlock[] = []
  let currentParagraph: string[] = []

  function flushParagraph(): void {
    const text = currentParagraph.join(" ").trim()
    if (text) {
      blocks.push({ type: "paragraph", level: 0, text })
    }
    currentParagraph = []
  }

  for (const rawLine of lines) {
    const line = rawLine.trim()

    if (!line) {
      flushParagraph()
      continue
    }

    const headingMatch = line.match(/^(#{1,6})\s+(.+)$/)
    if (headingMatch) {
      flushParagraph()
      const level = headingMatch[1].length
      blocks.push({ type: "heading", level, text: headingMatch[2].trim() })
      continue
    }

    currentParagraph.push(line)
  }

  flushParagraph()
  return blocks
}

export async function generateDocx(markdown: string): Promise<Buffer> {
  const blocks = parseMarkdownBlocks(markdown)
  const children: Paragraph[] = []

  for (const block of blocks) {
    if (block.type === "heading") {
      const headingLevel =
        block.level === 1
          ? HeadingLevel.HEADING_1
          : block.level === 2
            ? HeadingLevel.HEADING_2
            : block.level === 3
              ? HeadingLevel.HEADING_3
              : HeadingLevel.HEADING_4

      children.push(
        new Paragraph({
          text: block.text,
          heading: headingLevel,
          alignment: AlignmentType.LEFT,
          spacing: { after: 120 },
        }),
      )
    } else {
      const runs = parseBoldRuns(block.text).map(
        (run) =>
          new TextRun({
            text: run.text,
            bold: run.bold,
            color: BODY,
            font: "Georgia",
            size: 22, // 11pt
          }),
      )

      children.push(
        new Paragraph({
          children: runs,
          spacing: { after: 160 },
          alignment: AlignmentType.JUSTIFIED,
        }),
      )
    }
  }

  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: AI_DISCLOSURE,
          color: "#B49F90",
          font: "Georgia",
          size: 18, // 9pt
          italics: true,
        }),
      ],
      spacing: { before: 400 },
    }),
  )

  const doc = new DocxDocument({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: MARGIN * 20, // 1 inch in twips (1 twip = 1/20 point)
              right: MARGIN * 20, // 1 inch in twips (1 twip = 1/20 point)
              bottom: MARGIN * 20, // 1 inch in twips (1 twip = 1/20 point)
              left: MARGIN * 20, // 1 inch in twips (1 twip = 1/20 point)
            },
          },
        },
        children,
      },
    ],
  })

  return Packer.toBuffer(doc)
}

const pdfStyles = StyleSheet.create({
  page: {
    padding: MARGIN,
    backgroundColor: "#FFFDF9",
  },
  heading1: {
    fontSize: 22,
    marginBottom: 12,
    color: INK,
    fontWeight: "bold",
  },
  heading2: {
    fontSize: 18,
    marginBottom: 10,
    color: INK,
    fontWeight: "bold",
  },
  heading3: {
    fontSize: 15,
    marginBottom: 8,
    color: INK,
    fontWeight: "bold",
  },
  paragraph: {
    fontSize: 11,
    lineHeight: 1.6,
    marginBottom: 12,
    color: BODY,
    textAlign: "justify",
  },
  bold: {
    fontWeight: "bold",
  },
  disclosure: {
    fontSize: 8,
    color: "#B49F90",
    marginTop: 24,
    fontStyle: "italic",
  },
})

function renderPdfText(runs: ParsedRun[]): React.ReactElement[] {
  return runs.map((run, index) =>
    React.createElement(
      PdfText,
      { key: index, style: run.bold ? pdfStyles.bold : undefined },
      run.text,
    ),
  )
}

export async function generatePdf(markdown: string): Promise<Buffer> {
  const blocks = parseMarkdownBlocks(markdown)

  const pageChildren = blocks.map((block, index) => {
    if (block.type === "heading") {
      const style =
        block.level === 1
          ? pdfStyles.heading1
          : block.level === 2
            ? pdfStyles.heading2
            : pdfStyles.heading3

      return React.createElement(PdfText, { key: index, style }, block.text)
    }

    return React.createElement(
      PdfView,
      { key: index, style: pdfStyles.paragraph },
      renderPdfText(parseBoldRuns(block.text)),
    )
  })

  pageChildren.push(
    React.createElement(
      PdfText,
      { key: "disclosure", style: pdfStyles.disclosure },
      AI_DISCLOSURE,
    ),
  )

  const document = React.createElement(
    PdfDocument,
    { title: "Karmic Reading", author: "Karmic Interpreter" },
    React.createElement(PdfPage, { size: "A4", style: pdfStyles.page }, pageChildren),
  )

  return renderToBuffer(document)
}

type EventCategory = "Opportunity" | "Warning" | "Transition" | "Advice"

// Spec §8.1 reminder tuning per category (seconds before the event).
const ALARM_SECONDS: Record<EventCategory, number> = {
  Transition: 604800, // 7 days
  Warning: 604800, // 7 days
  Opportunity: 259200, // 3 days
  Advice: 259200, // 3 days
}

// Vimshottari period lengths (years) — antardashas slice each mahadasha
// proportionally: subPeriod = mahadasha × (subLordYears / 120).
const VIMSHOTTARI_YEARS: Record<string, number> = {
  Ketu: 7,
  Venus: 20,
  Sun: 6,
  Moon: 10,
  Mars: 7,
  Rahu: 18,
  Jupiter: 16,
  Saturn: 19,
  Mercury: 17,
}
const DASHA_LORD_ORDER = [
  "Ketu",
  "Venus",
  "Sun",
  "Moon",
  "Mars",
  "Rahu",
  "Jupiter",
  "Saturn",
  "Mercury",
]

function classifyDateContext(markdown: string, index: number): EventCategory {
  // Sentence-scale context: wider windows let distant keywords bleed across
  // unrelated dates.
  const context = markdown
    .slice(Math.max(0, index - 70), index + 80)
    .toLowerCase()
  if (
    /\b(avoid|caution|careful|challeng|delay|tension|friction|risk|difficult|strain)\b/.test(
      context,
    )
  ) {
    return "Warning"
  }
  if (
    /\b(auspicious|favorable|favourable|opportunit|excellent|ideal|golden|powerful|best|window|ripe)\b/.test(
      context,
    )
  ) {
    return "Opportunity"
  }
  return "Advice"
}

interface ReportDate {
  date: string
  category: EventCategory
}

const MONTH_NUMBERS: Record<string, number> = {
  january: 1,
  february: 2,
  march: 3,
  april: 4,
  may: 5,
  june: 6,
  july: 7,
  august: 8,
  september: 9,
  october: 10,
  november: 11,
  december: 12,
}

/** Future, valid dates in the report (ISO and natural English forms), classified by context. */
function extractReportDates(markdown: string): ReportDate[] {
  const seen = new Set<string>()
  const results: ReportDate[] = []
  const today = new Date()
  today.setHours(0, 0, 0, 0)

  function consider(
    year: number,
    month: number,
    day: number,
    contextIndex: number,
  ): void {
    const parsed = new Date(Date.UTC(year, month - 1, day))
    if (
      Number.isNaN(parsed.getTime()) ||
      parsed.getUTCMonth() !== month - 1 ||
      parsed.getUTCDate() !== day
    ) {
      return
    }
    if (parsed < today) return
    const iso = parsed.toISOString().slice(0, 10)
    if (seen.has(iso)) return
    seen.add(iso)
    results.push({
      date: iso,
      category: classifyDateContext(markdown, contextIndex),
    })
  }

  // ISO form: 2027-11-02
  const isoPattern = /\b(\d{4})-(\d{2})-(\d{2})\b/g
  let match: RegExpExecArray | null
  while ((match = isoPattern.exec(markdown)) !== null) {
    consider(Number(match[1]), Number(match[2]), Number(match[3]), match.index)
  }

  // Natural forms: "November 2, 2027" and "2 November 2027"
  const monthNames = Object.keys(MONTH_NUMBERS).join("|")
  const mdyPattern = new RegExp(
    `\\b(${monthNames})\\s+(\\d{1,2})(?:st|nd|rd|th)?,?\\s+(\\d{4})\\b`,
    "gi",
  )
  while ((match = mdyPattern.exec(markdown)) !== null) {
    consider(
      Number(match[3]),
      MONTH_NUMBERS[match[1].toLowerCase()],
      Number(match[2]),
      match.index,
    )
  }
  const dmyPattern = new RegExp(
    `\\b(\\d{1,2})(?:st|nd|rd|th)?\\s+(${monthNames}),?\\s+(\\d{4})\\b`,
    "gi",
  )
  while ((match = dmyPattern.exec(markdown)) !== null) {
    consider(
      Number(match[3]),
      MONTH_NUMBERS[match[2].toLowerCase()],
      Number(match[1]),
      match.index,
    )
  }

  return results
}

/** Antardasha (sub-period) start dates within one mahadasha. */
function antardashaStarts(
  mahaLord: string,
  start: Date,
  end: Date,
): Array<{ lord: string; start: Date }> {
  const totalYears = VIMSHOTTARI_YEARS[mahaLord]
  if (!totalYears) return []
  const durationMs = end.getTime() - start.getTime()
  if (durationMs <= 0) return []

  const startIdx = Math.max(0, DASHA_LORD_ORDER.indexOf(mahaLord))
  const subs: Array<{ lord: string; start: Date }> = []
  let cursor = start.getTime()
  for (let i = 0; i < DASHA_LORD_ORDER.length; i++) {
    const subLord = DASHA_LORD_ORDER[(startIdx + i) % DASHA_LORD_ORDER.length]
    subs.push({ lord: subLord, start: new Date(cursor) })
    cursor += (VIMSHOTTARI_YEARS[subLord] / 120) * durationMs
  }
  return subs
}

function isoDay(date: Date): string {
  return date.toISOString().slice(0, 10)
}

export async function generateIcs(
  markdown: string,
  chartData?: ChartData,
): Promise<Buffer> {
  const calendar = ical({ name: "Karmic Interpreter Guidance" })
  const seen = new Set<string>()
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  // Antardashas flood decades; cap their horizon at 5 years out.
  const subHorizon = new Date(today)
  subHorizon.setFullYear(subHorizon.getFullYear() + 5)

  function addEvent(
    dateStr: string,
    summary: string,
    description: string,
    category: EventCategory,
  ): void {
    const key = `${dateStr}|${summary}`
    if (seen.has(key)) return
    seen.add(key)

    calendar.createEvent({
      start: dateStr,
      allDay: true,
      summary: `Karmic ${category.toLowerCase()}: ${summary}`,
      description,
      categories: [{ name: category }],
      alarms: [
        {
          trigger: ALARM_SECONDS[category],
          description: `${summary} is approaching.`,
        },
      ],
    })
  }

  // 1. Windows named in the report, classified by their surrounding language.
  for (const { date, category } of extractReportDates(markdown)) {
    addEvent(
      date,
      category === "Advice" ? "Guided day" : `${category} window`,
      "Insight from your Karmic Interpreter reading.",
      category,
    )
  }

  // 2. Dasha transitions: mahadasha starts (Transition) plus antardasha
  //    sub-periods for the next five years (Advice).
  for (const period of chartData?.dashaTimeline ?? []) {
    const start = new Date(period.start)
    const end = new Date(period.end)
    if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime())) continue

    if (start >= today) {
      addEvent(
        isoDay(start),
        `${period.lord} Mahadasha begins`,
        `The ${period.lord} period (${period.years} years) opens. From your Karmic Interpreter reading.`,
        "Transition",
      )
    }

    for (const sub of antardashaStarts(period.lord, start, end)) {
      if (sub.start < today || sub.start > subHorizon) continue
      addEvent(
        isoDay(sub.start),
        `${period.lord}–${sub.lord} begins`,
        `The ${sub.lord} sub-period within your ${period.lord} Mahadasha opens. From your Karmic Interpreter reading.`,
        "Advice",
      )
    }
  }

  return Buffer.from(calendar.toString(), "utf-8")
}
