/**
 * Email delivery service.
 *
 * Sends completion emails via the Resend SDK.
 */

import { Resend } from "resend"

function getAppUrl(): string {
  return process.env.APP_URL?.replace(/\/$/, "") ?? "http://localhost:3000"
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;")
}

export async function sendCompletionEmail(
  to: string,
  name: string,
  readingId: string,
): Promise<void> {
  try {
    const apiKey = process.env.RESEND_API_KEY
    const fromEmail = process.env.FROM_EMAIL

    if (!apiKey || !fromEmail) {
      console.warn(
        "[EMAIL] RESEND_API_KEY or FROM_EMAIL is missing; skipping completion email.",
      )
      return
    }

    const appUrl = getAppUrl()
    const readingUrl = `${appUrl}/reading/${readingId}`

    // Reports are private blobs; downloads go through the app's download
    // route, which streams them after checking the reading's expiry.
    const downloadButtons = [
      {
        label: "Download DOCX",
        url: `${appUrl}/api/reading/${readingId}/download?type=docx`,
      },
      {
        label: "Download PDF",
        url: `${appUrl}/api/reading/${readingId}/download?type=pdf`,
      },
      {
        label: "Add to Calendar",
        url: `${appUrl}/api/reading/${readingId}/download?type=ics`,
      },
    ]
      .map(
        (button) =>
          `<a href="${escapeHtml(button.url)}" style="display:inline-block;margin:8px 8px 8px 0;padding:12px 20px;background:#8B5E3C;color:#FFFFFF;text-decoration:none;border-radius:6px;font-weight:bold;">${escapeHtml(button.label)}</a>`,
      )
      .join("\n")

    const subject = "Your Karmic Interpreter reading is ready"

    const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escapeHtml(subject)}</title>
</head>
<body style="margin:0;padding:0;background:#FFF8F0;font-family:Georgia,serif;color:#331D01;">
  <table role="presentation" width="100%" cellspacing="0" cellpadding="0" border="0">
    <tr>
      <td align="center" style="padding:40px 20px;">
        <table role="presentation" width="600" cellspacing="0" cellpadding="0" border="0" style="background:#FFFFFF;border-radius:12px;overflow:hidden;box-shadow:0 4px 12px rgba(31,18,8,0.08);">
          <tr>
            <td style="padding:40px 40px 24px;">
              <h1 style="margin:0 0 16px;font-size:28px;color:#1F1208;">Your reading is ready, ${escapeHtml(name)}</h1>
              <p style="margin:0 0 24px;font-size:16px;line-height:1.6;">Your personalized Karmic Interpreter reading has been completed. You can view it online or download your reports below.</p>
              <p style="margin:0 0 24px;">
                <a href="${escapeHtml(readingUrl)}" style="display:inline-block;padding:14px 28px;background:#1F1208;color:#FFFFFF;text-decoration:none;border-radius:6px;font-weight:bold;">View Your Reading</a>
              </p>
              ${downloadButtons ? `<div style="margin-top:24px;padding-top:24px;border-top:1px solid #E8DED4;">${downloadButtons}</div>` : ""}
              <p style="margin:24px 0 0;font-size:13px;color:#8B5E3C;">If the buttons above do not work, copy and paste this link into your browser:<br /><a href="${escapeHtml(readingUrl)}" style="color:#8B5E3C;">${escapeHtml(readingUrl)}</a></p>
              <p style="margin:16px 0 0;font-size:12px;color:#B49F90;">Generated by SoliVana AI — for reflection and education, not advice. Your reading expires 30 days after creation.</p>
            </td>
          </tr>
        </table>
      </td>
    </tr>
  </table>
</body>
</html>`

    const resend = new Resend(apiKey)

    const { error } = await resend.emails.send({
      from: fromEmail,
      to,
      // The owner always receives a copy of reading delivery emails.
      bcc: fromEmail,
      subject,
      html,
    })

    if (error) {
      console.error("[EMAIL] Resend returned an error:", error)
    }
  } catch (error) {
    console.error("[EMAIL] Failed to send completion email:", error)
    // Do not throw so the pipeline can still complete.
  }
}

export interface ShareEmailPayload {
  to: string
  ownerName: string
  readingId: string
  pdfBuffer: Buffer
}

/**
 * Sends a shared reading to a third party: the PDF report as an attachment
 * plus links to view online and download the other formats. Returns whether
 * the send succeeded so callers can surface failures (unlike the completion
 * email, which is fire-and-forget).
 */
export async function sendReportShareEmail({
  to,
  ownerName,
  readingId,
  pdfBuffer,
}: ShareEmailPayload): Promise<boolean> {
  try {
    const apiKey = process.env.RESEND_API_KEY
    const fromEmail = process.env.FROM_EMAIL

    if (!apiKey || !fromEmail) {
      console.warn(
        "[EMAIL] RESEND_API_KEY or FROM_EMAIL is missing; skipping share email.",
      )
      return false
    }

    const appUrl = getAppUrl()
    const readingUrl = `${appUrl}/reading/${readingId}`
    const safeName = ownerName.replace(/[\r\n]+/g, " ").trim().slice(0, 100)

    const downloadButtons = [
      {
        label: "Download DOCX",
        url: `${appUrl}/api/reading/${readingId}/download?type=docx`,
      },
      {
        label: "Add to Calendar",
        url: `${appUrl}/api/reading/${readingId}/download?type=ics`,
      },
    ]
      .map(
        (button) =>
          `<a href="${escapeHtml(button.url)}" style="display:inline-block;margin:8px 8px 8px 0;padding:12px 20px;background:#8B5E3C;color:#FFFFFF;text-decoration:none;border-radius:6px;font-weight:bold;">${escapeHtml(button.label)}</a>`,
      )
      .join("\n")

    const subject = `${safeName} shared their Karmic Interpreter reading with you`

    const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escapeHtml(subject)}</title>
</head>
<body style="margin:0;padding:0;background:#FFF8F0;font-family:Georgia,serif;color:#331D01;">
  <table role="presentation" width="100%" cellspacing="0" cellpadding="0" border="0">
    <tr>
      <td align="center" style="padding:40px 20px;">
        <table role="presentation" width="600" cellspacing="0" cellpadding="0" border="0" style="background:#FFFFFF;border-radius:12px;overflow:hidden;box-shadow:0 4px 12px rgba(31,18,8,0.08);">
          <tr>
            <td style="padding:40px 40px 24px;">
              <h1 style="margin:0 0 16px;font-size:28px;color:#1F1208;">${escapeHtml(safeName)} shared a reading with you</h1>
              <p style="margin:0 0 24px;font-size:16px;line-height:1.6;">${escapeHtml(safeName)} thought you'd enjoy their personalized Karmic Interpreter reading. The full PDF report is attached to this email, and you can also view it online.</p>
              <p style="margin:0 0 24px;">
                <a href="${escapeHtml(readingUrl)}" style="display:inline-block;padding:14px 28px;background:#1F1208;color:#FFFFFF;text-decoration:none;border-radius:6px;font-weight:bold;">View the Reading Online</a>
              </p>
              ${downloadButtons ? `<div style="margin-top:24px;padding-top:24px;border-top:1px solid #E8DED4;">${downloadButtons}</div>` : ""}
              <p style="margin:24px 0 0;font-size:13px;color:#8B5E3C;">This link expires 30 days after the reading was created.</p>
              <p style="margin:16px 0 0;font-size:12px;color:#B49F90;">Generated by SoliVana AI — for reflection and education, not advice.</p>
            </td>
          </tr>
        </table>
      </td>
    </tr>
  </table>
</body>
</html>`

    const resend = new Resend(apiKey)

    const { error } = await resend.emails.send({
      from: fromEmail,
      to,
      // The owner always receives a copy of reading delivery emails.
      bcc: fromEmail,
      subject,
      html,
      attachments: [
        {
          filename: "karmic-reading.pdf",
          content: pdfBuffer.toString("base64"),
        },
      ],
    })

    if (error) {
      console.error("[EMAIL] Resend returned an error:", error)
      return false
    }

    return true
  } catch (error) {
    console.error("[EMAIL] Failed to send share email:", error)
    return false
  }
}
